def load(calendar_id):
    """این تابع را در Django shell یا management command صدا بزنید."""
    from yourapp.models import Calendar, CalendarException  # نام app را اصلاح کنید

    calendar = Calendar.objects.get(pk=calendar_id)
    created_count = 0
    skipped_count = 0

    for date_str, description in HOLIDAYS:
        y, m, d = map(int, date_str.split("-"))
        obj, created = CalendarException.objects.get_or_create(
            calendar=calendar,
            date=date(y, m, d),
            defaults={"is_working": False, "description": description},
        )
        if created:
            created_count += 1
        else:
            skipped_count += 1

    print(f"✅ {created_count} تعطیلی جدید ثبت شد.")
    print(f"↷ {skipped_count} مورد از قبل موجود بود و رد شد.")


if __name__ == "__main__":
    # هنگام اجرا با: python manage.py shell < load_iran_holidays.py
    # calendar_id مورد نظر خود را جایگزین کنید
    load(calendar_id=1)
